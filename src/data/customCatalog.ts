function product(
  id: string,
  title: string,
  sku: string,
  categoryId: string,
  categoryName: string,
  price: number,
  stock: number,
  totalSold: number,
  description: string,
  tags: string[],
  productType: Product['productType'] = 'digital',
): Product {
  return {
    id,
    title,
    slug: sku.toLowerCase(),
    shortDescription: description,
    description,
    categoryId,
    categoryName,
    productType,
    productSource: 'manual',
    price,
    compareAtPrice: Math.round(price * 1.15),
    discountPercent: 13,
    images: [image],
    variations: [{
      id: `${id}-default`,
      type: 'Package',
      value: 'Standard Access',
      price,
      stock,
      sku,
      isAvailable: true,
      normalizedKey: `${id}+package+standard_access`,
    }],
    instantDeliveryFormat: 'license_key',
    deliveryInstructions: 'Your digital access details will be shown after payment and sent to your email.',
    tags,
    isFeatured: true,
    isTrending: totalSold > 100,
    isTrendingWeek: totalSold > 150,
    isBestSeller: totalSold > 100,
    isFlashDeal: price <= 1000,
    isLimitedTime: false,
    totalSold,
    offerBadgeText: totalSold > 100 ? 'BEST SELLER' : undefined,
    offerBadgeColor: totalSold > 100 ? 'yellow' : undefined,
    status: 'published',
    rating: 4.8,
    reviewCount: Math.max(8, Math.round(totalSold / 4)),
    reviews: [],
    stock,
    lowStockThreshold: Math.min(20, Math.max(5, Math.round(stock * 0.1))),
    sku,
    createdAt: now,
    updatedAt: now,
  };
}

